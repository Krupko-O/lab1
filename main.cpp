#include <iostream>

using namespace std;

int main() {
    // --- Завдання Begin16 ---
    cout << "--- Завдання Begin16 ---" << endl;
    
    // Декларація змінних
    double x, y;
    
    // Введення даних
    cout << "Введіть значення x: ";
    cin >> x;
    
    // Оскільки складні функції використовувати не можна, рахуємо степені множенням
    // Спочатку знаходимо x у квадраті (x^2)
    double x2 = x * x;
    
    // Потім знаходимо x у шостому степені (x^6), перемноживши x^2 тричі
    double x6 = x2 * x2 * x2;
    
    // Рахуємо фінальний результат функції y = 3x^6 - 6x^2 - 7
    y = 3 * x6 - 6 * x2 - 7;
    
    // Вивід результату
    cout << "Значення функції y = " << y << endl << endl;

    // --- Завдання Begin13 ---
    cout << "--- Завдання Begin13 ---" << endl;
    
    // Декларація змінних
    double A, B, C;
    
    // Введення даних
    cout << "Введіть координату точки A: ";
    cin >> A;
    cout << "Введіть координату точки B: ";
    cin >> B;
    cout << "Введіть координату точки C (між A і B): ";
    cin >> C;
    
    // Рахуємо добуток довжин відрізків AC і BC
    // Добуток (A - C) * (C - B) завжди дасть правильну додатну площу без використання if
    double product = (A - C) * (C - B);
    
    // Вивід результату
    cout << "Добуток довжин відрізків AC і BC = " << product << endl << endl;

    // --- Завдання Begin11 ---
    cout << "--- Завдання Begin11 ---" << endl;
    
    // Декларація змінних
    double L, R, S;
    const double pi = 3.14; // Задаємо значення пі за умовою
    
    // Введення даних
    cout << "Введіть довжину кола L: ";
    cin >> L;
    
    // З формули L = 2 * pi * R знаходимо радіус R
    R = L / (2 * pi);
    
    // Знаходимо площу круга S = pi * R^2
    S = pi * R * R;
    
    // Вивід результатів
    cout << "Радіус кола R = " << R << endl;
    cout << "Площа круга S = " << S << endl;

    return 0;
}
