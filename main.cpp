#include <iostream>

using namespace std;

int main()
{
    // Задача Begin19
    // Декларація змінних:
    // A - вхідне число, b та c - дві допоміжні змінні
    double A, b, c;

    // Введення змінної A
    cout << "Введіть число A: ";
    cin >> A;
    cout << endl; // Перенос рядка для красивого виводу

    // Обчислення та почерговий вивід (рівно 5 операцій множення)
    b = A * A;          // 1-ше множення: A^2
    cout << "A^2 = " << b << endl;

    c = b * A;          // 2-ге множення: A^3
    cout << "A^3 = " << c << endl;

    b = c * b;          // 3-тє множення: A^5
    cout << "A^5 = " << b << endl;

    c = b * b;          // 4-те множення: A^10
    cout << "A^10 = " << c << endl;

    b = c * b;          // 5-те множення: A^15
    cout << "A^15 = " << b << endl;

    return 0;
}